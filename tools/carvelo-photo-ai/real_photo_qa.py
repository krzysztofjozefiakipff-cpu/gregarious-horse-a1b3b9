#!/usr/bin/env python3
"""Offline CARVAMO acceptance gate for real-photo segmentation masks.

No network, no database, no production writes. Supply alpha masks generated by
the SAME segmentation pipeline as the worker. A successful report validates
only wheel-contact geometry; it does not certify a 3D render or full E2E.
Usage:
 python real_photo_qa.py --manifest examples.json --output qa.json

Manifest:
 {"cases":[{"id":"front-three-quarter","kind":"exterior",
 "mask":"masks/front.png","expected_x":[0.28,0.72],"tolerance":0.08},
 {"id":"interior-dashboard","kind":"interior"}]}
Expected points are manually reviewed, normalized horizontal tire positions.
"""
import argparse
import json
import sys
from pathlib import Path
from PIL import Image
from studio_compose import _contact_centers

def check_case(case, base):
    ident = str(case["id"])
    kind = case["kind"]
    if kind == "interior":
        return {"id":ident,"kind":kind,"status":"skipped",
                "reason":"interior_does_not_require_wheel_detection"}
    if kind != "exterior":
        return {"id":ident,"kind":kind,"status":"fail","reason":"unknown_kind"}
    if not case.get("mask"):
        return {"id":ident,"kind":kind,"status":"fail","reason":"mask_missing"}
    path = (base / str(case["mask"])).resolve()
    if not path.is_relative_to(base.resolve()):
        return {"id":ident,"kind":kind,"status":"fail","reason":"unsafe_mask_path"}
    if not path.is_file():
        return {"id":ident,"kind":kind,"status":"fail","reason":"mask_file_missing"}
    try:
        with Image.open(path) as source:
            if source.width * source.height > 12_000_000:
                raise ValueError("mask_pixel_limit")
            alpha = source.getchannel("A") if "A" in source.getbands() else source.convert("L")
            detected = list(_contact_centers(alpha))
    except (ValueError, OSError) as exc:
        return {"id":ident,"kind":kind,"status":"fail","reason":str(exc)[:100]}
    expected = case.get("expected_x")
    if not isinstance(expected,list) or len(expected)<2 or any(
            not isinstance(x,(int,float)) or not 0 <= x <= 1 for x in expected):
        return {"id":ident,"kind":kind,"status":"needs_review",
                "reason":"manual_reference_missing","detected_x":detected}
    tolerance = float(case.get("tolerance",0.08))
    if not 0 < tolerance <= 0.15:
        return {"id":ident,"kind":kind,"status":"fail","reason":"invalid_tolerance"}
    # Each reference must match a DIFFERENT detection, not just the nearest one.
    remaining = detected[:]
    matched = []
    for reference in sorted(expected):
        if not remaining:
            break
        nearest = min(range(len(remaining)),key=lambda i:abs(remaining[i]-reference))
        candidate = remaining.pop(nearest)
        if abs(candidate-reference) <= tolerance:
            matched.append(candidate)
    return {"id":ident,"kind":kind,"status":"pass" if len(matched)==len(expected) else "fail",
            "reason":"contact_geometry_verified" if len(matched)==len(expected) else "wheel_reference_mismatch",
            "detected_x":detected,"expected_x":expected,"tolerance":tolerance}

def evaluate(manifest):
    manifest = Path(manifest).resolve()
    data = json.loads(manifest.read_text(encoding="utf-8"))
    cases = data["cases"]
    if not isinstance(cases,list) or not cases:
        raise ValueError("cases_required")
    results = [check_case(case,manifest.parent) for case in cases]
    counts = {status:sum(x["status"]==status for x in results)
              for status in ("pass","fail","needs_review","skipped")}
    exterior = [x for x in results if x["kind"]=="exterior"]
    passed = bool(exterior) and all(x["status"]=="pass" for x in exterior)
    return {"gate":"real_photo_wheel_geometry","passed":passed,
            "counts":counts,"cases":results,
            "scope":"offline_mask_geometry_only_not_e2e_or_3d"}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest",required=True)
    parser.add_argument("--output",required=True)
    args = parser.parse_args()
    report = evaluate(args.manifest)
    Path(args.output).write_text(json.dumps(report,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    print(json.dumps({"passed":report["passed"],"counts":report["counts"]}))
    return 0 if report["passed"] else 1

if __name__=="__main__":
    sys.exit(main())
