import { chromium, devices } from "playwright";
import assert from "node:assert/strict";
const id="11111111-2222-4333-8444-555555555555";
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({...devices["iPhone 13"],locale:"pl-PL"});
const errors=[];page.on("pageerror",e=>errors.push(e.message));
let submitted=null;
await page.route("**/rest/v1/**",route=>{const url=route.request().url();if(url.includes("/cv_offers?"))return route.fulfill({status:200,contentType:"application/json",body:JSON.stringify([{id,brand:"OMODA",model:"OMODA 5",body:"SUV",fuel:"Benzyna",gross_price:109900,dealer_id:"66666666-7777-4888-8999-000000000000",status:"published",special:false}])});if(url.includes("/cv_dealers?"))return route.fulfill({status:200,contentType:"application/json",body:JSON.stringify([{id:"66666666-7777-4888-8999-000000000000",name:"Salon Testowy",active:true}])});if(url.includes("/cv_preview_offer_details?"))return route.fulfill({status:200,contentType:"application/json",body:JSON.stringify([{version_name:"Comfort",discount_terms:"Rabat testowy",purchase_terms:"Zakup gotówkowy",financing_terms:"Leasing testowy",pickup_city:"Poznań",availability_confirmed:false}])});console.log("UNMOCKED API",url);return route.fulfill({status:404,body:"[]"})});
await page.route("**/functions/v1/carvamo-preview-lead",async route=>{submitted=route.request().postDataJSON();await route.fulfill({status:201,contentType:"application/json",body:JSON.stringify({ok:true,reference:"TEST1234"})})});
await page.goto("http://127.0.0.1:8765/?offer="+id+"&utm_source=meta&utm_campaign=test_mobile",{waitUntil:"networkidle"});
assert.equal(new URL(page.url()).searchParams.get("utm_source"),"meta");
assert.equal(new URL(page.url()).searchParams.get("offer"),id);
await page.getByRole("heading",{name:"OMODA OMODA 5"}).waitFor();
await page.getByText("Comfort").waitFor();
assert.match((await page.locator(".detail-price").innerText()).replace(/\s/g," "),/109 900 zł/);
await page.getByText("Rabat testowy").waitFor();
await page.getByText("Zakup gotówkowy").waitFor();
await page.getByText("Leasing testowy").waitFor();
await page.getByText("Zapytaj o dostępność").first().waitFor();
assert.equal(await page.getByText("Dostępność potwierdzona").count(),0);
await page.locator('[name="full_name"]').fill("Test Klient");
await page.locator('[name="email"]').fill("test@example.invalid");
await page.locator('[name="phone"]').fill("500600700");
await page.locator('[name="consent"]').check();
await page.getByRole("button",{name:"Zapytaj o tę ofertę"}).click();
await page.getByText("TEST1234").waitFor();
assert.equal(submitted.offer_id,id);
assert.equal(submitted.attribution.utm_source,"meta");
assert.equal(submitted.attribution.utm_campaign,"test_mobile");
assert.equal(submitted.full_name,"Test Klient");
const viewport=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,inner:window.innerWidth}));
assert.ok(viewport.scroll<=viewport.inner+2,"Mobile horizontal overflow: "+JSON.stringify(viewport));
assert.deepEqual(errors,[]);
console.log("MOBILE E2E PASS: campaign URL → offer detail → terms → mocked lead payload → confirmation");
await browser.close();
